"""Render a job command and submit it detached on the target."""

from __future__ import annotations

import datetime as _dt
import re
import secrets
import shlex

from .catalog import RepoRef
from .contract import job_id_for
from .transport import Remote

PLACEHOLDER = re.compile(r"\{(repo|job|job_id|project_root|run_id|extra|env_name)\}")


def render(template: str, values: dict[str, str]) -> str:
    """Substitute {placeholders}; every value is shell-quoted.

    Quoting is what makes a path with spaces or a stray ';' harmless — the only
    unquoted text is whatever the user typed as an explicit extra argument.
    """
    def repl(match: re.Match) -> str:
        key = match.group(1)
        return shlex.quote(values.get(key, ""))
    return PLACEHOLDER.sub(repl, template)


def build_run_id(repo_name: str, job: str) -> str:
    stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    slug = re.sub(r"[^a-z0-9]+", "-", job_id_for(job).lower()).strip("-")[:40]
    return f"{stamp}-{slug}-{secrets.token_hex(2)}"


def run_dir_for(repo_path: str, run_id: str) -> str:
    return f"{repo_path}/.machine_mgr/runs/{run_id}"


def build_start_script(run_dir: str, shell: str = "bash") -> str:
    """Starter that backgrounds command.sh and records its pid in the run dir.

    ``cd X && setsid cmd &`` would background the whole and-list, so $! would be
    a subshell pid and the pid file would land in the wrong directory. Doing the
    cd here, in a script, keeps $! pointing at the real process.
    """
    return (
        "#!/usr/bin/env bash\n"
        f"cd {shlex.quote(run_dir)} || exit 1\n"
        f"setsid {shell} command.sh > log 2>&1 < /dev/null &\n"
        "echo $! > pid\n"
    )


def build_script(*, repo_path: str, descriptor, values: dict[str, str],
                 run_dir: str, extra: str) -> str:
    """The exact shell script that will run on the target."""
    workdir = descriptor.runner.workdir or "."
    abs_workdir = repo_path if workdir in (".", "") else f"{repo_path}/{workdir.strip('./')}"
    lines = [
        "#!/usr/bin/env bash",
        "# generated by machine_mgr — do not edit",
        "set -o pipefail",
        f"cd {shlex.quote(abs_workdir)}",
    ]
    for key, raw in descriptor.runner.env.items():
        lines.append(f"export {key}={render(raw, values)}")
    exit_path = shlex.quote(run_dir + "/exit")
    lines.append(f"trap 'rc=$?; echo $rc > {exit_path}' EXIT")
    command = render(descriptor.runner.command, values)
    if extra:
        command = f"{command} {extra}"
    lines.append(command)
    lines.append("")
    return "\n".join(lines)


def submit(*, remote: Remote, repo: RepoRef, job: str, extra: str,
           project_root: str, submitter_sha: str = "") -> dict:
    """Freeze the job and start it detached. Returns the run record fields."""
    descriptor = repo.descriptor
    run_id = build_run_id(repo.name, job)
    run_dir = run_dir_for(repo.path, run_id)
    job_abs = f"{repo.path}/{job}"
    values = {
        "repo": repo.name,
        "job": job_abs,
        "job_id": job_id_for(job),
        "project_root": project_root,
        "run_id": run_id,
        "extra": extra,
        "env_name": descriptor.env.name,
    }
    script = build_script(repo_path=repo.path, descriptor=descriptor,
                          values=values, run_dir=run_dir, extra=extra)

    remote.run(f"mkdir -p {shlex.quote(run_dir)}")
    remote.write_file(f"{run_dir}/command.sh", script, mode="755")
    remote.write_file(f"{run_dir}/start.sh", build_start_script(run_dir, descriptor.runner.shell),
                      mode="755")
    remote.run(f"cp {shlex.quote(job_abs)} {shlex.quote(run_dir + '/submitted.yaml')}")
    if descriptor.env.name:
        remote.write_file(f"{run_dir}/env_name", descriptor.env.name + "\n")

    start = f"bash {shlex.quote(run_dir + '/start.sh')} && sleep 1 && cat {shlex.quote(run_dir + '/pid')}"
    pid = remote.run(start).strip().splitlines()[-1]

    return {
        "id": run_id,
        "repo": repo.name,
        "repo_path": repo.path,
        "job": job,
        "run_dir": run_dir,
        "pid": pid,
        "status": "running",
        "exit_code": None,
        "started": _dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "git_head": submitter_sha,
        "command": values["extra"],
        "submitted": _dt.datetime.now().astimezone().isoformat(timespec="seconds"),
    }
